// Builds web/forecast-lib.js from the server's forecast code (one source for server, app screen and widget).
// usage: node forecast-lib/build.mjs [--check]   (--check: fail when the committed file is out of date)
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "fs";
import { fileURLToPath } from "url";
import path from "path";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, "..", "..", "web", "forecast-lib.js");
const r = await build({
  entryPoints: [path.join(here, "entry.mjs")], bundle: true, format: "iife", minify: true, target: "es2017",
  legalComments: "none", write: false, charset: "utf8",
  banner: { js: "/* Ne Giysem? forecast builder for the app (MET Norway -> Open-Meteo shape). Generated by tests/forecast-lib/build.mjs from web/functions/_lib; do not edit. Includes tz-lookup (CC0). */" },
});
const text = r.outputFiles[0].text;
if (process.argv.includes("--check")) {
  let old = "";
  try { old = readFileSync(out, "utf8"); } catch (e) {}
  if (old !== text) { console.error("web/forecast-lib.js is out of date: run node tests/forecast-lib/build.mjs"); process.exit(1); }
  console.log("web/forecast-lib.js up to date (" + text.length + " bytes)");
} else {
  writeFileSync(out, text);
  console.log("wrote web/forecast-lib.js (" + text.length + " bytes)");
}
